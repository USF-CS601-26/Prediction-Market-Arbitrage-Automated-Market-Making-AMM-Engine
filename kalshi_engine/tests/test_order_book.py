"""
tests/test_order_book.py

Unit tests for OrderBook, run entirely offline against the synthetic
fixture generated by mock_kalshi_feed.py — no network/live Kalshi
connection required.

Run with: pytest tests/ -v
(requires a conftest.py at the project root so pytest can resolve
`from order_book import OrderBook` from inside tests/)
"""

import json
import pytest
from order_book import OrderBook
from models import OrderBookSnapshot, OrderBookDelta


@pytest.fixture
def replayed_book():
    """
    Builds a fresh OrderBook and replays the full mock_feed.json event
    log through it (one snapshot, then all deltas in order). Any test
    that takes `replayed_book` as an argument gets this pre-populated
    book automatically.
    """
    book = OrderBook(market_id="KXPRES-24", exchange="kalshi")
    with open("fixtures/mock_feed.json") as f:
        events = json.load(f)

    for e in events:
        # pop "type" off since it's not a field on OrderBookSnapshot/Delta —
        # it's only there to tell this loop which method to call
        e_type = e.pop("type")
        if e_type == "snapshot":
            book.apply_snapshot(OrderBookSnapshot(**e, exchange="kalshi"))
        else:
            book.apply_delta(OrderBookDelta(**e, exchange="kalshi"))
    return book


def test_top_of_book_not_empty(replayed_book):
    """
    After replaying a snapshot + 20 random deltas, confirms:
      1. Both sides of the book still have at least one level (nothing
         got wiped out by a level-removal bug).
      2. The book is never crossed — best bid must be strictly less
         than best ask, which is the fundamental sanity invariant of
         a real order book.
    """
    bid, ask = replayed_book.get_top_of_book()
    assert bid is not None
    assert ask is not None
    assert bid.price < ask.price


def test_sequence_gap_raises():
    """
    Confirms apply_delta detects a missing message. Applies a snapshot
    at sequence=1, then feeds a delta claiming sequence=5 (skipping
    2, 3, 4) and asserts this raises ValueError rather than silently
    applying the out-of-order update. This is the mechanism that
    protects the live book from corruption if the WebSocket drops a
    message.
    """
    book = OrderBook("X", "kalshi")
    book.apply_snapshot(OrderBookSnapshot(
        market_id="X", exchange="kalshi", timestamp="2026-01-01T00:00:00Z",
        sequence=1, bids=[], asks=[],
    ))
    bad_delta = OrderBookDelta(
        market_id="X", exchange="kalshi", timestamp="2026-01-01T00:00:01Z",
        sequence=5, side="bid", price="0.5", size="10",
    )
    with pytest.raises(ValueError):
        book.apply_delta(bad_delta)