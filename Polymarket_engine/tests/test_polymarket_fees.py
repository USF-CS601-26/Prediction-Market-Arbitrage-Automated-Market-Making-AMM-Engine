"""
tests/test_polymarket_fees.py

Taker fee checks. The expected values in the first test are copied from the
example table on https://docs.polymarket.com/trading/fees (100 shares), so
they were calculated by Polymarket, not by our code. The rest were worked out
by hand; the arithmetic is in each comment.
"""

import tomllib
from decimal import Decimal

import pytest

from polymarket.config import FeeSchedule, PairConfig
from polymarket.fees import fee_fn, taker_fee
from polymarket.gamma import to_toml_section


def fees(rate: str, enabled: bool = True, exponent: str = "1") -> FeeSchedule:
    return FeeSchedule(enabled=enabled, rate=Decimal(rate), exponent=Decimal(exponent))


@pytest.mark.parametrize("rate, price, expected", [
    ("0.07", "0.50", "1.75"), ("0.07", "0.30", "1.47"), ("0.07", "0.10", "0.63"),   # crypto
    ("0.05", "0.50", "1.25"), ("0.05", "0.30", "1.05"), ("0.05", "0.10", "0.45"),   # sports
    ("0.04", "0.50", "1.00"), ("0.04", "0.30", "0.84"), ("0.04", "0.10", "0.36"),   # politics, finance
])
def test_matches_polymarket_docs_table(rate, price, expected):
    assert taker_fee(Decimal("100"), Decimal(price), fees(rate)) == Decimal(expected)


def test_fee_is_symmetric_around_one_half():
    # 0.30 * 0.70 == 0.70 * 0.30, so both pay 100 * 0.04 * 0.21 = 0.84
    assert taker_fee(Decimal("100"), Decimal("0.30"), fees("0.04")) == taker_fee(Decimal("100"), Decimal("0.70"), fees("0.04"))


def test_fee_at_our_pairs_price():
    # 250 * 0.04 * 0.42 * 0.58 = 250 * 0.04 * 0.2436 = 2.436
    assert taker_fee(Decimal("250"), Decimal("0.42"), fees("0.04")) == Decimal("2.436")


def test_disabled_market_pays_nothing():
    # like the Netanyahu market: feesEnabled = false, so the rate is ignored
    assert taker_fee(Decimal("1000"), Decimal("0.42"), fees("0.04", enabled=False)) == 0


def test_zero_rate_pays_nothing():
    assert taker_fee(Decimal("1000"), Decimal("0.42"), fees("0")) == 0


def test_zero_shares_pay_nothing():
    assert taker_fee(Decimal("0"), Decimal("0.42"), fees("0.04")) == 0


def test_rounds_to_five_decimal_places():
    # 7 * 0.04 * 0.33 * 0.67 = 0.061908 -> 0.06191 (half-up)
    assert taker_fee(Decimal("7"), Decimal("0.33"), fees("0.04")) == Decimal("0.06191")


def test_fee_below_smallest_unit_rounds_to_zero():
    # 0.1 * 0.04 * 0.001 * 0.999 = 0.000003996, below 0.00001 -> 0
    assert taker_fee(Decimal("0.1"), Decimal("0.001"), fees("0.04")) == 0


def test_exponent_applies_to_price_component():
    # our reading of the docs: 100 * 0.04 * (0.5 * 0.5) ** 2 = 100 * 0.04 * 0.0625 = 0.25
    assert taker_fee(Decimal("100"), Decimal("0.50"), fees("0.04", exponent="2")) == Decimal("0.25")


@pytest.mark.parametrize("price", ["0", "1", "1.2", "-0.1"])
def test_rejects_impossible_price(price):
    with pytest.raises(ValueError):
        taker_fee(Decimal("10"), Decimal(price), fees("0.04"))


def test_rejects_negative_shares():
    with pytest.raises(ValueError):
        taker_fee(Decimal("-1"), Decimal("0.42"), fees("0.04"))


# ---- fitting the spread engine (executable_spread.FeeFn is fee(contracts, price)) ----

def test_fee_fn_matches_taker_fee():
    fee = fee_fn(fees("0.04"))
    # same answer as test_fee_at_our_pairs_price: 250 * 0.04 * 0.42 * 0.58 = 2.436
    assert fee(Decimal("250"), Decimal("0.42")) == taker_fee(Decimal("250"), Decimal("0.42"), fees("0.04")) == Decimal("2.436")


def test_swapped_arguments_raise_instead_of_miscalculating():
    # price first, shares second is the old order: 100 lands in the price slot and fails the check
    with pytest.raises(ValueError):
        taker_fee(Decimal("0.42"), Decimal("100"), fees("0.04"))
    with pytest.raises(ValueError):
        fee_fn(fees("0.04"))(Decimal("0.42"), Decimal("100"))


# ---- fee settings generated by the Gamma lookup tool ----

GAMMA_MARKET = {
    "conditionId": "0xabc",
    "outcomes": '["Yes", "No"]',
    "clobTokenIds": '["111", "222"]',
    "orderPriceMinTickSize": 0.001,
}


def _load(market: dict) -> PairConfig:
    return PairConfig.model_validate(tomllib.loads('pair_id = "x"\n' + to_toml_section("s", market)))


def test_gamma_section_with_fees_loads():
    pair = _load({**GAMMA_MARKET, "feesEnabled": True,
                  "feeSchedule": {"exponent": 1, "rate": 0.04, "takerOnly": True, "rebateRate": 0.25}})
    assert pair.polymarket.fees == FeeSchedule(enabled=True, rate=Decimal("0.04"), exponent=Decimal("1"))
    assert pair.polymarket.tick_size == Decimal("0.001")


def test_gamma_section_without_fees_loads():
    pair = _load({**GAMMA_MARKET, "feesEnabled": False, "feeSchedule": None})
    assert pair.polymarket.fees == FeeSchedule(enabled=False, rate=Decimal("0"), exponent=Decimal("1"))
